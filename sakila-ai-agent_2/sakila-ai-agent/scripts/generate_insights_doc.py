"""Write docs/INSIGHTS_VERIFIED.md: the team's six insights recomputed from the database,
with checks of the written report, metrics, caveats and follow-up SQL.  Run: python scripts/generate_insights_doc.py"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src import insights as ins  # noqa: E402

ch = ins.chronology()
L = ["# The six insights, verified against the Sakila database", "",
     f"_Generated by `scripts/generate_insights_doc.py`. Data: {ch['distinct_rental_dates']} recorded rental dates in "
     f"{len(ch['rental_bursts'])} bursts; {ch['gap_days']}-day gap ({ch['gap_from'][:10]} to {ch['gap_to'][:10]}); "
     f"no rentals in {', '.join(ch['months_with_no_rentals'])}._", ""]
for i in range(1, 7):
    x = ins.INSIGHTS[i]()
    L += [f"## Insight {i}: {x['title']}", f"**Business question:** {x['business_question']}", "", "**Verified findings**"]
    L += [f"- {f}" for f in x["verified_findings"]]
    L += ["", "**Check of the written report**"] + [f"- {f}" for f in x["report_check"]]
    L += ["", "**Metrics to watch**"] + [f"- `{k}`: {v}" for k, v in x["metrics_to_watch"].items()]
    L += ["", "**Caveats**"] + [f"- {c}" for c in x["caveats"]]
    L += ["", "**Recommendations (hypotheses to test)**"] + [f"- {r}" for r in x["recommendations_hypotheses"]]
    L += ["", "**Follow-up SQL**", "```sql", x["follow_up_sql"], "```", ""]
L += ["## What the data cannot show", ""] + [f"- **{t}**: {d}" for t, d in ins.DATA_LIMITS]
(ROOT / "docs" / "INSIGHTS_VERIFIED.md").write_text("\n".join(L), encoding="utf-8")
print("written docs/INSIGHTS_VERIFIED.md")
